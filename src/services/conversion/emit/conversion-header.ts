import type { DiagramFormat } from "@/constants/diagram-formats";
import type { AppLocale } from "@/constants/i18n";
import type { ConversionReport } from "@/services/conversion/conversion-report";

export function buildConversionHeaderComment(
  report: ConversionReport,
  locale: AppLocale,
): string {
  const kindChanged = Boolean(report.targetKind && report.targetKind !== report.kind);
  const from = kindChanged ? `${report.sourceFormat} (${report.kind})` : report.sourceFormat;
  const to = kindChanged ? `${report.targetFormat} (${report.targetKind})` : report.targetFormat;
  const losses = report.lossIds.join(", ");

  if (locale === "ru") {
    return [
      `' Сгенерировано конвертером Code2Graph`,
      `' ${from} → ${to} (уровень ${report.level})`,
      `' Потери: ${losses}`,
    ].join("\n");
  }

  return [
    `' Generated by Code2Graph converter`,
    `' ${from} → ${to} (level ${report.level})`,
    `' Losses: ${losses}`,
  ].join("\n");
}

export function buildMermaidConversionHeader(
  report: ConversionReport,
  locale: AppLocale,
): string {
  return buildConversionHeaderComment(report, locale)
    .split("\n")
    .map((line) => `%% ${line.replace(/^' /, "")}`)
    .join("\n");
}

export function buildD2ConversionHeader(
  report: ConversionReport,
  locale: AppLocale,
): string {
  return buildConversionHeaderComment(report, locale)
    .split("\n")
    .map((line) => `# ${line.replace(/^' /, "")}`)
    .join("\n");
}

export function buildSlashConversionHeader(
  report: ConversionReport,
  locale: AppLocale,
): string {
  return buildConversionHeaderComment(report, locale)
    .split("\n")
    .map((line) => `// ${line.replace(/^' /, "")}`)
    .join("\n");
}

export function buildGraphmlConversionHeader(
  report: ConversionReport,
  locale: AppLocale,
): string {
  return buildConversionHeaderComment(report, locale)
    .split("\n")
    .map((line) => `<!-- ${line.replace(/^' /, "")} -->`)
    .join("\n");
}

export function wrapConvertedSource(
  source: string,
  format: DiagramFormat,
  report: ConversionReport,
  locale: AppLocale,
): string {
  if (format === "mermaid") {
    return `${buildMermaidConversionHeader(report, locale)}\n${source}`;
  }

  if (format === "d2") {
    return `${buildD2ConversionHeader(report, locale)}\n${source}`;
  }

  if (format === "structurizr" || format === "wiremark") {
    return `${buildSlashConversionHeader(report, locale)}\n${source}`;
  }

  if (format === "graphml") {
    return source.replace(
      /<\?xml[^>]*>\s*/,
      (match) => `${match}${buildGraphmlConversionHeader(report, locale)}\n`,
    );
  }

  if (source.startsWith("@start")) {
    return source.replace(
      /@start\w+/,
      (match) => `${match}\n${buildConversionHeaderComment(report, locale)}`,
    );
  }

  return `${buildConversionHeaderComment(report, locale)}\n${source}`;
}
